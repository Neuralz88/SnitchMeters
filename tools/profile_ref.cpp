// profile_ref <in.f32> <sampleRate> <name> <out.h>
// Measures a reference track and writes its profile as dsp/ConcussionProfile.h.
#include <cstdio>
#include <cstdlib>
#include "RawAudio.h"
#include "dsp/ProfileBuilder.h"

static void writeArray(FILE* f, const float* v) {
    std::fprintf(f, "        { ");
    for (int i = 0; i < snitch::kBands; ++i) std::fprintf(f, "%.2ff%s", v[i], i + 1 < snitch::kBands ? ", " : " },\n");
}

int main(int argc, char** argv) {
    if (argc < 5) { std::fprintf(stderr, "usage: profile_ref <in.f32> <sampleRate> <name> <out.h>\n"); return 2; }
    std::vector<float> L, R;
    if (! loadRawStereo(argv[1], L, R)) { std::fprintf(stderr, "cannot read %s\n", argv[1]); return 1; }
    const double sr = std::atof(argv[2]);

    const snitch::RefProfile p = snitch::buildProfile(L.data(), R.data(), L.size(), sr, argv[3]);
    if (! p.valid) { std::fprintf(stderr, "not enough loud audio to profile\n"); return 1; }

    FILE* f = std::fopen(argv[4], "w");
    if (f == nullptr) { std::fprintf(stderr, "cannot write %s\n", argv[4]); return 1; }
    std::fprintf(f, "// Generated by tools/make_profile.ps1 - do not edit.\n"
                    "// Measurements of the reference track only; no audio.\n"
                    "#pragma once\n#include \"Profile.h\"\n\nnamespace snitch {\n"
                    "inline const RefProfile& concussionProfile() {\n    static const RefProfile p = {\n"
                    "        \"%s\",\n        true,\n", p.name);
    writeArray(f, p.band); writeArray(f, p.bandLo); writeArray(f, p.bandHi);
    std::fprintf(f, "        %.2ff, %.2ff, %.2ff, %.3ff, %.1ff, %.4ff\n    };\n    return p;\n}\n} // namespace snitch\n",
                 p.lufs, p.truePeakDb, p.psr, p.corrLow, p.clipRate, p.dc);
    std::fclose(f);

    std::printf("%s\n  integrated %.1f LUFS, true peak %+.2f dBTP, PSR %.1f, low correlation %.2f, clip runs %.0f/s, DC %.3f\n",
                p.name, p.lufs, p.truePeakDb, p.psr, p.corrLow, p.clipRate, p.dc);
    for (int i = 0; i < snitch::kBands; ++i)
        std::printf("  %7.0f Hz  %6.1f  (%6.1f .. %6.1f)\n", snitch::bandCentre(i), p.band[i], p.bandLo[i], p.bandHi[i]);
    return 0;
}
